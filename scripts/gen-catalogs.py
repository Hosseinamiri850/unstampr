def keys(d, p=""):
    out = set()
    for k, v in d.items():
        kk = f"{p}.{k}" if p else k
        if isinstance(v, dict):
            out |= keys(v, kk)
        else:
            out.add(kk)
    return out


def write(name, data, en_keys):
    ck = keys(data)
    missing = en_keys - ck
    extra = ck - en_keys
    if missing or extra:
        print(f"{name}: MISSING={sorted(missing)} EXTRA={sorted(extra)}")
        sys.exit(1)
    with open(f"messages/{name}.json", "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"{name}: ok ({len(ck)} keys)")


